# ==============================================================================
# src/structures/Nulls.jl
# Null ensembles and the match-versus-rhyme decision.
#
# The decision rule is the user's own exercise 6.1 from rna_biofilm_toy,
# reused verbatim in form: a floor set by the spread of the null contrasts,
# at FLOOR_MULTIPLE standard deviations, with the decision declared BEFORE any
# real pair is scored.
#
# A resemblance that is not closer than the null floor is a RHYME.
# Only a resemblance that clears the floor is a MATCH CANDIDATE, and even then
# it is a geometric statement, never a homology or a mechanism.
# ==============================================================================

const FLOOR_MULTIPLE = 2.0

"""
    floor_from_sham(sham_contrasts; multiple=FLOOR_MULTIPLE) -> Float64

Decision floor from the spread of the null contrasts. Form preserved from
`rna_biofilm_toy/analysis/sandbox_implementations.jl:175-182`.
"""
function floor_from_sham(sham_contrasts; multiple::Real=FLOOR_MULTIPLE)
    all(isfinite, sham_contrasts) || throw(ArgumentError("non-finite sham contrast"))
    length(sham_contrasts) >= 2 || throw(ArgumentError("at least two sham contrasts required"))
    multiple > 0 || throw(ArgumentError("multiple must be positive"))
    s = std(sham_contrasts; corrected=true)
    (isfinite(s) && s > 0) || throw(ArgumentError("invalid sham spread"))
    r = multiple * s
    isfinite(r) || throw(ArgumentError("invalid floor"))
    return r
end

"decide(effect, floor) -> Bool. Strictly greater; ties do not clear the floor."
decide(effect::Real, flr::Real) = effect > flr

# --- idealized Caspar-Klug shells -------------------------------------------

"The 60 rotation matrices of the icosahedral group I, built from its generators."
function icosahedral_group()
    phi = (1 + sqrt(5)) / 2
    # 5-fold about an axis through a vertex of the icosahedron
    ax5 = normalize([1.0, phi, 0.0])
    ax2 = [1.0, 0.0, 0.0]
    rot(axis, ang) = begin
        a = normalize(axis); x, y, z = a
        c, s, C = cos(ang), sin(ang), 1 - cos(ang)
        [c+x*x*C   x*y*C-z*s  x*z*C+y*s;
         y*x*C+z*s c+y*y*C    y*z*C-x*s;
         z*x*C-y*s z*y*C+x*s  c+z*z*C]
    end
    gens = [rot(ax5, 2pi/5), rot(ax2, pi)]
    G = [Matrix{Float64}(I, 3, 3)]
    changed = true
    while changed && length(G) < 60
        changed = false
        for g in gens, M in copy(G)
            P = g * M
            if !any(maximum(abs.(P - X)) < 1e-6 for X in G)
                push!(G, P); changed = true
            end
        end
    end
    return G
end

"""
    caspar_klug_shell(T, radius_angstrom) -> Vector{Vector{Float64}}

Subunit centroids for an idealized T-number shell: 60*T points generated by
applying the icosahedral group to T seed positions inside one asymmetric unit,
then projecting onto a sphere of the requested radius. This is a lattice
reference for comparison, not a structural model of any particular virus.
"""
function caspar_klug_shell(T::Int, radius_angstrom::Real; seed::Int=20260,
                           radius_sample::Union{Nothing,Vector{Float64}}=nothing)
    T in ck_triangulation_numbers() || throw(ArgumentError("T=$(T) is not a valid Caspar-Klug triangulation number"))
    G = icosahedral_group()
    length(G) == 60 || error("icosahedral group construction produced $(length(G)) elements, expected 60")
    rng = Random.MersenneTwister(seed)
    # T seed points inside ONE spherical asymmetric unit, which is 1/60 of the
    # sphere and so has an angular diameter near 0.6 rad. A fixed minimum
    # separation cannot be satisfied for larger T inside that patch, so the
    # requirement starts generous and relaxes on failure, with a hard attempt
    # cap. (A fixed 0.35 threshold here is an infinite loop for T >= 7.)
    probe = normalize([0.0, 0.0, 1.0])
    into_au(v) = G[argmax([dot(g * v, probe) for g in G])] * v
    seeds = Vector{Vector{Float64}}()
    minsep = 0.30
    attempts = 0
    while length(seeds) < T
        attempts += 1
        if attempts > 4000
            minsep *= 0.5
            attempts = 0
            minsep < 1e-4 && throw(ArgumentError("cannot place $(T) seeds in one asymmetric unit"))
        end
        w = into_au(normalize(randn(rng, 3)))
        all(norm(w - s) > minsep for s in seeds) && push!(seeds, w)
    end
    # Radial jitter drawn from the real radial distribution, so the idealized
    # lattice is thickness-matched and the comparison is not decided by a
    # property the null cannot have.
    rng2 = Random.MersenneTwister(seed + 7919)
    pts = Vector{Vector{Float64}}()
    for g in G, s in seeds
        r = radius_sample === nothing ? radius_angstrom :
            radius_sample[rand(rng2, 1:length(radius_sample))]
        push!(pts, r .* (g * s))
    end
    return pts
end

"""
    random_sphere_shell(n, radius_angstrom; seed) -> Vector{Vector{Float64}}

n subunit centroids placed uniformly at random on a sphere of matched radius.
The size-and-count-matched null: anything a shell shares with this is shared by
every shell of that size, so it cannot be evidence of a common architecture.
"""
function random_sphere_shell(n::Int, radius_angstrom::Real; seed::Int=1,
                             radius_sample::Union{Nothing,Vector{Float64}}=nothing)
    rng = Random.MersenneTwister(seed)
    # A null placed at one exact radius has zero shell thickness, which no real
    # shell has. That single unmatched component separates every real structure
    # from every null by construction and makes the contrast meaningless, so the
    # radii are resampled from the real structure's own radial distribution
    # whenever one is supplied.
    rad(i) = radius_sample === nothing ? radius_angstrom :
             radius_sample[rand(rng, 1:length(radius_sample))]
    return [rad(i) .* normalize(randn(rng, 3)) for i in 1:n]
end

"""
    rewire_preserving_degree(nv, edges; seed, nswaps) -> Vector{Tuple{Int,Int}}

Degree-preserving double-edge swap. Keeps the degree sequence and destroys the
geometry, so it isolates what the contact graph's shape contributes beyond its
degree distribution.
"""
function rewire_preserving_degree(nv::Int, edges::Vector{Tuple{Int,Int}}; seed::Int=1, nswaps::Int=0)
    rng = Random.MersenneTwister(seed)
    E = collect(edges)
    m = length(E)
    m < 2 && return E
    nsw = nswaps > 0 ? nswaps : 10 * m
    present = Set{Tuple{Int,Int}}(map(e -> e[1] < e[2] ? e : (e[2], e[1]), E))
    for _ in 1:nsw
        i, j = rand(rng, 1:m), rand(rng, 1:m)
        i == j && continue
        (a, b) = E[i]; (c, d) = E[j]
        length(Set([a, b, c, d])) == 4 || continue
        n1 = a < d ? (a, d) : (d, a)
        n2 = c < b ? (c, b) : (b, c)
        (n1 in present || n2 in present) && continue
        o1 = a < b ? (a, b) : (b, a); o2 = c < d ? (c, d) : (d, c)
        delete!(present, o1); delete!(present, o2)
        push!(present, n1); push!(present, n2)
        E[i] = n1; E[j] = n2
    end
    return E
end

# --- scale-free descriptor vector and the decision ---------------------------

"""
    shape_fingerprint(centroids; cutoff_angstrom) -> Vector{Float64}

A deliberately scale-free descriptor vector, so that two shells are not judged
similar merely because they are the same size:

  1 normalized shell thickness        (p99 - p01) / p99 of the centroid radii
  2 relative shape anisotropy         kappa^2, 0 for a sphere
  3 mean degree of the contact graph
  4 beta_1 per subunit
  5 algebraic connectivity lambda_2
  6 interface classes per 60 subunits
"""
function shape_fingerprint(centroids::Vector{Vector{Float64}}; cutoff_angstrom::Real)
    C = reduce(hcat, centroids)
    n = length(centroids)
    cen = vec(sum(C, dims=2)) ./ n
    r = sort([norm(C[:, j] - cen) for j in 1:n])
    p(q) = r[clamp(ceil(Int, q * n), 1, n)]
    thick = p(0.99) > 0 ? (p(0.99) - p(0.01)) / p(0.99) : 0.0
    inert = inertia_descriptors(C)
    nv, edges = subunit_contact_graph(centroids, cutoff_angstrom)
    b0, b1, e = betti_numbers(nv, edges)
    lam = algebraic_connectivity(nv, edges)
    classes, _, _ = classify_interfaces(centroids, cutoff_angstrom; ndigits=0)
    return [thick,
            inert.relative_shape_anisotropy_dimensionless,
            nv > 0 ? 2 * e / nv : 0.0,
            nv > 0 ? b1 / nv : 0.0,
            lam,
            nv > 0 ? 60 * length(classes) / nv : 0.0]
end

"Standardize each component by the spread across a reference set, then Euclidean distance."
function fingerprint_distance(a::Vector{Float64}, b::Vector{Float64}, scale::Vector{Float64})
    s = [x > 0 ? x : 1.0 for x in scale]
    return sqrt(sum(((a .- b) ./ s) .^ 2))
end

"""
    match_or_rhyme(name_a, fp_a, name_b, fp_b, null_fps, scale) -> Dict

effect  = mean(distance from A to each null) - distance(A, B)
floor   = floor_from_sham(null distances)
verdict = MATCH_CANDIDATE if effect clears the floor, else RHYME

A match candidate is a geometric statement only. It never licenses an
`:is_homologous_to` or `:causally_connected` edge, which require a citation.
"""
function match_or_rhyme(name_a::String, fp_a::Vector{Float64},
                        name_b::String, fp_b::Vector{Float64},
                        null_fps::Vector{Vector{Float64}}, scale::Vector{Float64})
    dnull = [fingerprint_distance(fp_a, f, scale) for f in null_fps]
    dab = fingerprint_distance(fp_a, fp_b, scale)
    flr = floor_from_sham(dnull)
    effect = mean(dnull) - dab
    verdict = decide(effect, flr) ? "MATCH_CANDIDATE" : "RHYME"
    return Dict{String,Any}(
        "pair" => "$(name_a) vs $(name_b)",
        "distance_standardized_dimensionless" => dab,
        "null_distance_mean_dimensionless" => mean(dnull),
        "null_distance_std_dimensionless" => std(dnull; corrected=true),
        "n_nulls_count" => length(dnull),
        "effect_dimensionless" => effect,
        "floor_dimensionless" => flr,
        "floor_multiple_dimensionless" => FLOOR_MULTIPLE,
        "verdict" => verdict,
        "edge_type_licensed" => verdict == "MATCH_CANDIDATE" ? ":shares_geometry_with" : ":analogizes",
        "note" => "Geometric comparison only. Never licenses :is_homologous_to or " *
                  ":causally_connected, which require a citation field.",
    )
end
